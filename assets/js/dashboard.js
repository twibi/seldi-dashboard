/* SELDI CMS dashboard – single page, single chart with two views.
   View "By topic":   pick one of 6 topics  -> countries compared across years.
   View "By country": pick one of 10 countries -> all 6 topics as lines.
   Survey years + chart type apply to both views.
   Data: assets/js/data.js (generated by extract_data.py).
   Line colours: GNOME HIG palette (light 1 / dark 5 pairs, orange & brown
   used only where the hue count requires it). */
(function () {
  "use strict";

  var YEARS = [2001, 2002, 2014, 2016, 2019, 2021, 2023, 2025];

  /* Standalone site (index.html) sets this body class; a WordPress page
     embedding the dashboard does not — so we never touch the tab title,
     body background or anything else outside our own root when embedded. */
  var STANDALONE = document.body.classList.contains("seldi-standalone");

  /* Everything the dashboard renders lives inside this one wrapper, which
     carries all styles (see style.css) — a theme cannot bleed in and we
     cannot bleed out. */
  var root = document.createElement("div");
  root.className = "seldi-root";

  /* Insert the wrapper where this script sits in the document (i.e. inside
     the WordPress content block), falling back to end of body. */
  function placeRoot() {
    var s = document.currentScript;
    if (s && s.parentNode) s.parentNode.insertBefore(root, s);
    else document.body.appendChild(root);
  }

  var MAIN = "#2f3283";      // titles + topic buttons
  var ACCENT = "#ec7627";    // action / selector buttons

  /* GNOME HIG palette (developer.gnome.org/hig/reference/palette.html) */
  var GNOME = {
    blue1: "#99c1f1", blue5: "#1a5fb4",
    green1: "#8ff0a4", green5: "#26a269",
    yellow1: "#f9f06b", yellow5: "#e5a50a",
    orange5: "#c64600",
    red1: "#f66151", red5: "#a51d2d",
    purple1: "#dc8add", purple5: "#613583"
  };

  /* Countries (up to 10): light+dark pair per hue; orange/brown skipped. */
  var COUNTRY_COLORS = [
    GNOME.blue1, GNOME.blue5,
    GNOME.green1, GNOME.green5,
    GNOME.yellow1, GNOME.yellow5,
    GNOME.red1, GNOME.red5,
    GNOME.purple1, GNOME.purple5
  ];

  /* Topics (6): darker shade per hue; orange joins because a 6th hue is needed. */
  var TOPIC_COLORS = [
    GNOME.blue5,    // Corruption Pressure
    GNOME.green5,   // Involvement
    GNOME.yellow5,  // Acceptability
    GNOME.red5,     // Likelihood
    GNOME.purple5,  // Susceptibility
    GNOME.orange5   // Policy Response
  ];

  var data = window.SELDI || [];
  if (!data.length) {
    root.innerHTML =
      '<p style="padding:40px;font-family:sans-serif">No data loaded.</p>';
    placeRoot();
    return;
  }

  var ALL_COUNTRIES = [];
  data.forEach(function (t) {
    t.countries.forEach(function (c) {
      if (ALL_COUNTRIES.indexOf(c.country) === -1) ALL_COUNTRIES.push(c.country);
    });
  });

  /* ---------- state (years + type are shared by both views) ---------- */
  var state = {
    mode: "topic",            // "topic" | "country"
    topic: data[0].key,       // default: Corruption Pressure
    country: ALL_COUNTRIES[0],
    selected: {},             // topicKey -> {country: bool}
    from: 0,
    to: YEARS.length - 1,
    type: "line"
  };
  data.forEach(function (t) {
    var sel = {};
    t.countries.forEach(function (c) { sel[c.country] = true; });
    state.selected[t.key] = sel;
  });

  function current() {
    for (var i = 0; i < data.length; i++) {
      if (data[i].key === state.topic) return data[i];
    }
    return data[0];
  }

  /* Mini brand bar — standalone site only; a WordPress page has its own
     site header, so the embedded dashboard skips it. */
  if (STANDALONE) {
    var topbar = document.createElement("header");
    topbar.className = "topbar";
    var inner = document.createElement("div");
    inner.className = "topbar-inner";
    var brand = document.createElement("a");
    brand.className = "brand";
    brand.href = "#top";
    brand.innerHTML = 'SELDI <span>Corruption Monitoring System 2025</span>';
    inner.appendChild(brand);
    topbar.appendChild(inner);
    root.appendChild(topbar);
  }

  /* ---------- page scaffold ---------- */
  var page = document.createElement("main");
  page.className = "page";
  page.id = "top";

  var sec = document.createElement("section");
  /* NOT class "section": the Porto theme styles `.section` (grey background,
     padding, border) and would bleed onto this wrapper. */
  sec.className = "dash-section";
  sec.id = "dashboard";

  var head = document.createElement("div");
  head.className = "page-head";
  /* WordPress reserves h1 for the page title — embedded we start at h2. */
  var h1 = document.createElement(STANDALONE ? "h1" : "h2");
  h1.className = "seldi-title";
  var ins = document.createElement("div");
  ins.className = "insight";
  head.appendChild(h1);
  head.appendChild(ins);
  sec.appendChild(head);

  /* ---------- view switch + selector (above the card) ---------- */
  var viewBar = document.createElement("div");
  viewBar.className = "view-bar";

  var gV = document.createElement("div");
  gV.className = "control-group";
  gV.innerHTML = '<div class="control-label">View</div>';
  var segView = document.createElement("div");
  segView.className = "segmented";
  var byTopicBtn = mk("seg-btn on", "By topic");
  var byCountryBtn = mk("seg-btn", "By country");
  segView.appendChild(byTopicBtn);
  segView.appendChild(byCountryBtn);
  gV.appendChild(segView);
  viewBar.appendChild(gV);

  var selector = document.createElement("div");
  selector.className = "selector";

  /* 6 topic buttons */
  var topicBtns = document.createElement("div");
  topicBtns.className = "topic-bar inline";
  data.forEach(function (t, i) {
    var b = mk("topic-btn" + (i === 0 ? " on" : ""), t.nav);
    b.addEventListener("click", function () {
      state.topic = t.key;
      markOn(topicBtns, function (el, idx) {
        return data[idx].key === state.topic;
      });
      renderHeading();
      renderRow1();
      updateChart();
    });
    topicBtns.appendChild(b);
  });

  /* 10 country buttons */
  var countryBtns = document.createElement("div");
  countryBtns.className = "country-row";
  ALL_COUNTRIES.forEach(function (name) {
    var b = mk("topic-btn country-btn" + (name === state.country ? " on" : ""),
               name);
    b.addEventListener("click", function () {
      state.country = name;
      markOn(countryBtns, function (el) {
        return el.textContent === name;
      });
      renderHeading();
      updateChart();
    });
    countryBtns.appendChild(b);
  });

  selector.appendChild(topicBtns);
  selector.appendChild(countryBtns);
  countryBtns.style.display = "none";
  viewBar.appendChild(selector);
  sec.appendChild(viewBar);

  byTopicBtn.addEventListener("click", function () {
    if (state.mode === "topic") return;
    state.mode = "topic";
    byTopicBtn.classList.add("on");
    byCountryBtn.classList.remove("on");
    switchMode();
  });
  byCountryBtn.addEventListener("click", function () {
    if (state.mode === "country") return;
    state.mode = "country";
    byCountryBtn.classList.add("on");
    byTopicBtn.classList.remove("on");
    switchMode();
  });

  function switchMode() {
    var isTopic = state.mode === "topic";
    topicBtns.style.display = isTopic ? "" : "none";
    countryBtns.style.display = isTopic ? "none" : "";
    row1.style.display = isTopic ? "" : "none";
    renderHeading();
    renderRow1();
    updateChart();
  }

  /* ---------- filter card ---------- */
  var card = document.createElement("section");
  card.className = "card";

  /* Row 1: countries + All/None (By-topic view only) */
  var row1 = document.createElement("div");
  row1.className = "ctl-row";
  var gC = document.createElement("div");
  gC.className = "control-group grow";
  gC.innerHTML = '<div class="control-label">Countries</div>';
  var countryLine = document.createElement("div");
  countryLine.className = "country-line";
  var pills = document.createElement("div");
  pills.className = "countries";
  var actionsP = document.createElement("div");
  actionsP.className = "pill-actions";
  var allBtn = mk("mini-btn", "All");
  var noneBtn = mk("mini-btn", "None");
  actionsP.appendChild(allBtn);
  actionsP.appendChild(noneBtn);
  countryLine.appendChild(pills);
  countryLine.appendChild(actionsP);
  gC.appendChild(countryLine);
  row1.appendChild(gC);
  card.appendChild(row1);

  allBtn.addEventListener("click", function () {
    var sel = state.selected[state.topic];
    current().countries.forEach(function (c) { sel[c.country] = true; });
    syncPills();
    updateChart();
  });
  noneBtn.addEventListener("click", function () {
    var sel = state.selected[state.topic];
    current().countries.forEach(function (c) { sel[c.country] = false; });
    syncPills();
    updateChart();
  });

  function renderRow1() {
    pills.innerHTML = "";
    if (state.mode !== "topic") return;
    current().countries.forEach(function (c, idx) {
      var b = document.createElement("button");
      b.type = "button";
      b.style.setProperty("--seldi-pill", COUNTRY_COLORS[idx % COUNTRY_COLORS.length]);
      b.className =
        "country-pill" + (state.selected[state.topic][c.country] ? " on" : "");
      b.innerHTML = '<span class="dot"></span>';
      b.appendChild(document.createTextNode(c.country));
      b.addEventListener("click", function () {
        state.selected[state.topic][c.country] =
          !state.selected[state.topic][c.country];
        b.classList.toggle("on", state.selected[state.topic][c.country]);
        updateChart();
      });
      pills.appendChild(b);
    });
    row1.style.borderBottom = "";
  }

  function syncPills() {
    var sel = state.selected[state.topic];
    Array.prototype.forEach.call(pills.children, function (b, idx) {
      b.classList.toggle("on", !!sel[current().countries[idx].country]);
    });
  }

  /* Row 2: survey years + chart type + Reset / Save as PNG — always one row */
  var row2 = document.createElement("div");
  row2.className = "ctl-row options";

  var gY = document.createElement("div");
  gY.className = "control-group";
  gY.innerHTML = '<div class="control-label">Survey years</div>';
  var yearsBox = document.createElement("div");
  yearsBox.className = "years";
  var fromSel = document.createElement("select");
  var toSel = document.createElement("select");
  YEARS.forEach(function (y, idx) {
    var o1 = document.createElement("option");
    o1.value = idx;
    o1.textContent = y;
    fromSel.appendChild(o1);
    toSel.appendChild(o1.cloneNode(true));
  });
  fromSel.value = state.from;
  toSel.value = state.to;
  fromSel.addEventListener("change", function () {
    state.from = Math.min(+fromSel.value, state.to);
    fromSel.value = state.from;
    updateChart();
  });
  toSel.addEventListener("change", function () {
    state.to = Math.max(+toSel.value, state.from);
    toSel.value = state.to;
    updateChart();
  });
  var dash = document.createElement("span");
  dash.textContent = "–";
  yearsBox.appendChild(fromSel);
  yearsBox.appendChild(dash);
  yearsBox.appendChild(toSel);
  gY.appendChild(yearsBox);
  row2.appendChild(gY);

  var gT = document.createElement("div");
  gT.className = "control-group";
  gT.innerHTML = '<div class="control-label">Chart type</div>';
  var seg = document.createElement("div");
  seg.className = "segmented";
  var lineBtn = mk("seg-btn on", "Line");
  var barBtn = mk("seg-btn", "Bar");
  seg.appendChild(lineBtn);
  seg.appendChild(barBtn);
  gT.appendChild(seg);
  row2.appendChild(gT);
  lineBtn.addEventListener("click", function () {
    state.type = "line";
    lineBtn.classList.add("on");
    barBtn.classList.remove("on");
    updateChart();
  });
  barBtn.addEventListener("click", function () {
    state.type = "bar";
    barBtn.classList.add("on");
    lineBtn.classList.remove("on");
    updateChart();
  });

  var spacer = document.createElement("div");
  spacer.className = "spacer";
  row2.appendChild(spacer);

  var gA = document.createElement("div");
  gA.className = "control-group actions-group";
  gA.innerHTML = '<div class="control-label">&nbsp;</div>';
  var act = document.createElement("div");
  act.className = "actions";
  var resetBtn = mk("btn", "Reset");
  var pngBtn = mk("btn primary", "Save as PNG");
  act.appendChild(resetBtn);
  act.appendChild(pngBtn);
  gA.appendChild(act);
  row2.appendChild(gA);

  resetBtn.addEventListener("click", function () {
    var sel = state.selected[state.topic];
    current().countries.forEach(function (c) { sel[c.country] = true; });
    state.from = 0;
    state.to = YEARS.length - 1;
    state.type = "line";
    fromSel.value = 0;
    toSel.value = state.to;
    lineBtn.classList.add("on");
    barBtn.classList.remove("on");
    if (state.mode !== "topic") {
      state.mode = "topic";
      byTopicBtn.classList.add("on");
      byCountryBtn.classList.remove("on");
      topicBtns.style.display = "";
      countryBtns.style.display = "none";
      row1.style.display = "";
    }
    markOn(topicBtns, function (el, idx) {
      return data[idx].key === state.topic;
    });
    renderHeading();
    renderRow1();
    updateChart();
  });

  card.appendChild(row2);

  /* ---------- chart ---------- */
  var wrap = document.createElement("div");
  wrap.className = "chart-wrap";
  var canvas = document.createElement("canvas");
  wrap.appendChild(canvas);
  var emptyMsg = document.createElement("div");
  emptyMsg.className = "empty-msg";
  wrap.appendChild(emptyMsg);
  card.appendChild(wrap);
  sec.appendChild(card);
  page.appendChild(sec);

  root.appendChild(page);
  placeRoot();

  /* ---------- helpers ---------- */
  function mk(cls, text) {
    var el = document.createElement("button");
    el.type = "button";
    el.className = cls;
    if (text) el.textContent = text;
    return el;
  }
  function markOn(container, test) {
    Array.prototype.forEach.call(container.children, function (el, idx) {
      el.classList.toggle("on", !!test(el, idx));
    });
  }

  if (typeof Chart === "undefined") {
    wrap.innerHTML =
      '<p style="color:#2f3283">Chart.js failed to load (internet/CDN ' +
      'required). Check the connection and reload.</p>';
    return;
  }

  Chart.defaults.font.family = '"Segoe UI", Arial, Helvetica, sans-serif';
  Chart.defaults.color = "#4b5563";

  function baseOptions() {
    return {
      responsive: true,
      maintainAspectRatio: false,
      devicePixelRatio: 2,              // sharp PNG export
      animation: { duration: 250 },
      interaction: { mode: "index", intersect: false },
      plugins: {
        legend: {
          position: "bottom",
          labels: { usePointStyle: true, pointStyle: "circle", padding: 16 }
        },
        tooltip: {
          callbacks: {
            label: function (ctx) {
              var v = ctx.parsed.y;
              return v === null
                ? ctx.dataset.label + ": not surveyed"
                : ctx.dataset.label + ": " + v + "%";
            }
          }
        }
      },
      scales: {
        y: {
          beginAtZero: true,
          title: { display: true, text: "Share of population 18+ (%)" },
          ticks: { callback: function (v) { return v + "%"; } },
          grid: { color: "#eceff4" }
        },
        x: { title: { display: true, text: "Survey year" }, grid: { display: false } }
      }
    };
  }

  function pct(v) { return v === null ? null : +(v * 100).toFixed(1); }

  function buildConfig() {
    var years = YEARS.slice(state.from, state.to + 1);
    var datasets = [];

    if (state.mode === "topic") {
      var t = current();
      var sel = state.selected[t.key];
      t.countries.forEach(function (c, idx) {
        if (!sel[c.country]) return;
        var color = COUNTRY_COLORS[idx % COUNTRY_COLORS.length];
        datasets.push(series(c.country, color,
          years.map(function (y) { return pct(c.values[YEARS.indexOf(y)]); })));
      });
    } else {
      data.forEach(function (t, i) {
        var row = null;
        t.countries.forEach(function (c) {
          if (c.country === state.country) row = c;
        });
        if (!row) return;               // country not covered by this topic
        var vals = years.map(function (y) { return pct(row.values[YEARS.indexOf(y)]); });
        if (vals.every(function (v) { return v === null; })) return;
        datasets.push(series(t.label, TOPIC_COLORS[i % TOPIC_COLORS.length], vals));
      });
    }

    return {
      type: state.type,
      data: { labels: years, datasets: datasets },
      options: baseOptions()
    };
  }

  function series(label, color, vals) {
    var base = { label: label, data: vals,
                 borderColor: color, backgroundColor: color };
    if (state.type === "line") {
      base.borderWidth = 2.5;
      base.pointRadius = 3.5;
      base.pointHoverRadius = 6;
      base.spanGaps = false;   // gap = year not surveyed
      base.tension = 0.15;
    } else {
      base.borderWidth = 0;
      base.borderRadius = 3;
    }
    return base;
  }

  var chart = new Chart(canvas.getContext("2d"), buildConfig());

  function updateChart() {
    var cfg = buildConfig();
    chart.data = cfg.data;
    chart.options = cfg.options;
    chart.config.type = state.type;
    chart.update();

    if (!cfg.data.datasets.length) {
      emptyMsg.textContent = state.mode === "topic"
        ? "Select at least one country to display the chart."
        : "No survey data for this country in the selected year range.";
      emptyMsg.style.display = "flex";
    } else {
      emptyMsg.style.display = "none";
    }
  }

  /* ---------- heading per view ---------- */
  function renderHeading() {
    if (state.mode === "topic") {
      var t = current();
      h1.textContent = t.title;
      ins.textContent = t.insight || "";
      ins.style.display = t.insight ? "" : "none";
      if (STANDALONE) document.title = t.title + " · SELDI CMS Dashboard";
    } else {
      h1.textContent = "Corruption profile: " + state.country;
      ins.textContent =
        "All six SELDI CMS topics for " + state.country +
        " on one timeline, 2001–2025";
      ins.style.display = "";
      if (STANDALONE) {
        document.title =
          "Corruption profile: " + state.country + " · SELDI CMS Dashboard";
      }
    }
  }

  /* ---------- PNG export ---------- */
  function exportPNG() {
    var meta;
    if (state.mode === "topic") {
      var t = current();
      meta = { title: t.title, insight: t.insight,
               filename: "seldi-" + t.key + ".png" };
    } else {
      meta = { title: "Corruption profile: " + state.country,
               insight: "All six SELDI CMS topics on one timeline",
               filename: "seldi-profile-" +
                 state.country.toLowerCase().replace(/[^a-z0-9]+/g, "-") + ".png" };
    }

    var src = chart.canvas;
    var pad = 36;
    var headH = meta.insight ? 86 : 66;

    var out = document.createElement("canvas");
    out.width = src.width;
    out.height = src.height + headH;
    var ctx = out.getContext("2d");

    ctx.fillStyle = "#ffffff";
    ctx.fillRect(0, 0, out.width, out.height);

    ctx.fillStyle = MAIN;
    ctx.font = "700 26px 'Segoe UI', Arial, sans-serif";
    ctx.textBaseline = "top";
    ctx.fillText(meta.title, pad, pad - 6);
    if (meta.insight) {
      ctx.fillStyle = "#1c2430";
      ctx.font = "italic 17px 'Segoe UI', Arial, sans-serif";
      ctx.fillText(clip(ctx, meta.insight, out.width - pad * 2), pad, pad + 32);
    }

    ctx.drawImage(src, 0, headH);

    var a = document.createElement("a");
    a.href = out.toDataURL("image/png");
    a.download = meta.filename;
    a.click();
  }

  pngBtn.addEventListener("click", exportPNG);

  function clip(ctx, text, maxW) {
    if (ctx.measureText(text).width <= maxW) return text;
    var t = text;
    while (t.length > 1 && ctx.measureText(t + "…").width > maxW) {
      t = t.slice(0, -1);
    }
    return t + "…";
  }

  /* ---------- initial paint ---------- */
  renderHeading();
  renderRow1();
})();
